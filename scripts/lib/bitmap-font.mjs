/** 文本按行绘制到单通道位图（1 = 黑） */
export function drawText(bitmap, text, x, y, scale = 2) {
  const w = bitmap.width;
  const px = bitmap.data;
  let cx = x;
  for (const raw of String(text).toUpperCase()) {
    const glyph = FONT[raw] || FONT[' '];
    for (let row = 0; row < 7; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        if (!(glyph[row] & (1 << (4 - col)))) continue;
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            const px0 = cx + col * scale + dx;
            const py0 = y + row * scale + dy;
            if (px0 >= 0 && px0 < w && py0 >= 0 && py0 < bitmap.height) px[py0 * w + px0] = 1;
          }
        }
      }
    }
    cx += 6 * scale; // 5 列 + 1 列字距
  }
  return cx;
}

/** 文本像素宽度（用于居中） */
export const textWidth = (text, scale = 2) => String(text).length * 6 * scale - scale;

/** 把字模打印成图案，供人工核对（见 scripts/make-qrcode.mjs --dump-font） */
export function dumpFont(chars = Object.keys(FONT).join('')) {
  for (const ch of chars) {
    const g = FONT[ch];
    if (!g) continue;
    const rows = g.map((b) => Array.from({ length: 5 }, (_, i) => ((b >> (4 - i)) & 1) ? '#' : '.').join(''));
    console.log(`  "${ch}"   ${rows[0]}`);
    for (let i = 1; i < rows.length; i += 1) console.log(`        ${rows[i]}`);
  }
}
